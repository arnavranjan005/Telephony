// Google Calendar OAuth e2e test: boots the real Express app and drives the
// real /api/calendar/oauth/* routes with real HTTP requests. Only
// `googleapis`'s OAuth2 client is mocked (it needs a live Google OAuth
// consent flow, which can't run in CI) - googleCalendarClient.ts and
// calendarController's oauth handlers run unmocked. No Postgres writes
// happen on this path, so there's no DB fixture cleanup needed here.

const generateAuthUrl = jest.fn();
const getToken = jest.fn();
const setCredentials = jest.fn();
const oAuth2ClientConstructor = jest.fn();

jest.mock("googleapis", () => ({
  google: {
    auth: {
      OAuth2: jest.fn().mockImplementation((...args: unknown[]) => {
        oAuth2ClientConstructor(...args);
        return { generateAuthUrl, getToken, setCredentials };
      }),
    },
    calendar: jest.fn(() => ({ freebusy: { query: jest.fn() }, events: { insert: jest.fn(), delete: jest.fn() } })),
  },
}));

import request from "supertest";
import { createApp } from "../../api/src/app";
import { prisma } from "@telephony/database";
import { dialQueue } from "@telephony/queue";

const app = createApp();

afterAll(async () => {
  // Obliterate (not just close) - the "dial" queue/rate-limiter state lives in
  // Redis, shared by every *.e2e-test.ts file within one --runInBand run, so
  // leftover jobs from this file could otherwise bleed into the next file's
  // tests (competing for rate-limiter throughput, or racing a later
  // beforeEach's cleanup of the Postgres rows they still reference).
  await dialQueue.obliterate({ force: true });
  await dialQueue.close();
  await prisma.$disconnect();
});

beforeEach(() => {
  generateAuthUrl.mockReset();
  getToken.mockReset();
  setCredentials.mockReset();
  oAuth2ClientConstructor.mockReset();
});

describe("Google Calendar OAuth e2e (real Express routing, mocked googleapis OAuth2 client)", () => {
  it("returns the real consent URL generated by the OAuth2 client, requesting offline calendar access", async () => {
    generateAuthUrl.mockReturnValue("https://accounts.google.com/o/oauth2/v2/auth?mock=1");

    const res = await request(app).get("/api/calendar/oauth/url");

    expect(res.status).toBe(200);
    expect(res.body.url).toBe("https://accounts.google.com/o/oauth2/v2/auth?mock=1");
    expect(generateAuthUrl).toHaveBeenCalledWith(
      expect.objectContaining({
        access_type: "offline",
        prompt: "consent",
        scope: ["https://www.googleapis.com/auth/calendar"],
      })
    );
  });

  it("exchanges an OAuth code for a refresh token through the real callback route", async () => {
    getToken.mockResolvedValue({ tokens: { refresh_token: "mock-refresh-token-abc" } });

    const res = await request(app).get("/api/calendar/oauth/callback").query({ code: "auth-code-123" });

    expect(res.status).toBe(200);
    expect(res.body.refresh_token).toBe("mock-refresh-token-abc");
    expect(getToken).toHaveBeenCalledWith("auth-code-123");
  });

  it("rejects the callback with 400 when the 'code' query parameter is missing", async () => {
    const res = await request(app).get("/api/calendar/oauth/callback");

    expect(res.status).toBe(400);
    expect(getToken).not.toHaveBeenCalled();
  });
});
